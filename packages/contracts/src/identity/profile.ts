const assignedCountryCodes = new Set<string>(countryCodes);

export const CountryCode = Schema.String.check(
  Schema.makeFilter((code) => assignedCountryCodes.has(code), {
    message: "Enter the ISO 3166-1 alpha-2 code of a country",
  }),
).pipe(Schema.brand("CountryCode"));

export type CountryCode = typeof CountryCode.Type;

export const PersonName = Schema.Trimmed.check(
  Schema.isNonEmpty({ message: "Name is required" }),
  Schema.isMaxLength(100, { message: "Name must be at most 100 characters" }),
);

export const JobTitle = Schema.Trimmed.check(
  Schema.isMaxLength(100, { message: "Job title must be at most 100 characters" }),
);

export class Profile extends Schema.Class<Profile, { readonly brand: unique symbol }>("Profile")({
  firstName: PersonName,
  lastName: PersonName,
  avatarUrl: Schema.NullOr(Schema.String),
  jobTitle: JobTitle,
  team: Schema.NullOr(Team),
  country: Schema.NullOr(CountryCode),
}) {}
